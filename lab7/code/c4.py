# ```python
import PyPDF2

def detect_table_of_contents(pdf_path):
    """
    Определяет, используется ли в PDF файле оглавление вместо содержания.
    Использует конечный автомат для определения.

    Args:
        pdf_path (str): Путь к PDF файлу.

    Returns:
        list: Список строк с номерами страниц, если использовано оглавление.
              Возвращает пустой список, если использовано содержание или если файл не найден.
    """
    try:
        with open(pdf_path, 'rb') as pdf_file:
            reader = PyPDF2.PdfReader(pdf_file)
            num_pages = len(reader.pages)

            # Проверяем наличие заголовка. Оглавление обычно начинается с заголовка
            first_page = reader.pages[0]
            text = first_page.extract_text()

            # Простейшая реализация конечного автомата
            # Ищем строку "Оглавление" или "Содержание" (с учетом регистра)
            if "Оглавление" in text.upper() or "Содержание" in text.upper():
                # Находим оглавление.  Пример:  "Оглавление"
                title_line = next((line for line in text.splitlines() if "Оглавление" in line.upper()), None)
                
                if title_line:
                    #  Оцениваем, что это именно оглавление, на основе структуры текста
                    #  Это очень упрощенный пример, и его можно улучшить
                    if "Страницы" in title_line:  # Предполагаем, что в строке оглавления есть "Страницы"
                        print("Обнаружено оглавление.")
                        toc_lines = []
                        for page_num in range(1, num_pages + 1):
                            try:
                                page = reader.pages[page_num - 1]
                                page_text = page.extract_text()
                                # Ищем строку с номером страницы.  Это тоже упрощенно.
                                page_number_line = next((line for line in page_text.splitlines() if str(page_num) in line), None)
                                if page_number_line:
                                    toc_lines.append((page_number_line.strip(), page_num))
                            except IndexError:
                                pass  # Страница может быть не найдена.
                        return toc_lines
                    else:
                        print("Похоже на оглавление, но отсутствует строка 'Страницы'.")
                        return []
                else:
                    print("Строка оглавления не найдена.")
                    return []


            # Если не оглавление, считаем, что есть содержание
            print("Обнаружено содержание.")
            return []

    except FileNotFoundError:
        print(f"Файл не найден: {pdf_path}")
        return []
    except Exception as e:
        print(f"Ошибка при обработке PDF: {e}")
        return []


# Пример использования
pdf_file_path = "report.pdf"  # Замените на путь к вашему PDF файлу
toc = detect_table_of_contents(pdf_file_path)

if toc:
    print("Оглавление:")
    for line, page in toc:
        print(f"{line}, {page}")
else:
    print("Оглавление не найдено.")
